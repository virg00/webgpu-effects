#!/usr/bin/env node
// Generates the typed component functions (shaders/src/main/ets/components/components.ts) and the
// demo gallery catalog (entry rawfile catalog.json) from the upstream shader registry.
//
//   node scripts/gen-components.mjs upstream/registry.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const registryPath = resolve(process.argv[2] ?? `${root}/upstream/registry.mjs`);
const { shaderRegistry, deprecatedShaderNames } = await import(pathToFileURL(registryPath).href);

const quote = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const doc = (s) => String(s ?? '').replace(/\*\//g, '*\\/').replace(/\s+/g, ' ').trim();

function propType(p) {
  const ui = p.ui ?? {};
  const kinds = Array.isArray(ui.type) ? ui.type : [ui.type];
  const mappable = kinds.includes('map');
  const d = p.default;
  let t;
  switch (kinds[0]) {
    case 'select': {
      const opts = (ui.options ?? []).map((o) => (typeof o === 'object' ? o.value : o));
      t = opts.length ? [...new Set(opts.map((v) => (typeof v === 'number' ? String(v) : quote(v))))].join(' | ') : 'string';
      break;
    }
    case 'position': t = 'Position | PropDriver'; break;
    case 'gradient-stops': t = 'ColorStop[] | null'; break;
    case 'list': t = 'ListItem[]'; break;
    case 'checkbox': t = 'boolean'; break;
    case 'font-weight': t = 'number | string'; break;
    case 'range': t = 'number'; break;
    default:
      if (typeof d === 'number') t = 'number';
      else if (typeof d === 'boolean') t = 'boolean';
      else if (d && typeof d === 'object' && 'x' in d && 'y' in d) t = 'Position | PropDriver';
      else t = 'string';
  }
  if (mappable && !t.includes('PropDriver')) t += ' | PropDriver';
  return t;
}

const header = `// GENERATED by scripts/gen-components.mjs from the upstream shader registry — do not edit.
//
// Every function returns a ShaderNode for <ShaderView layers={[...]}>. Effects that filter their
// content take it as the second argument: Blur({ intensity: 30 }, [ImageTexture({ url })]).
import type { ShaderNode, LayerProps, Position, ColorStop, ListItem, PropDriver } from './types';

function node(type: string, props?: object, children?: ShaderNode[]): ShaderNode {
  const p: Record<string, Object> = {};
  let id: string | undefined;
  if (props) {
    for (const [k, v] of Object.entries(props)) {
      if (v === undefined) continue;
      if (k === 'id') id = v as string;
      else p[k] = v as Object;
    }
  }
  const n: ShaderNode = { type, props: p };
  if (id !== undefined) n.id = id;
  if (children && children.length) n.children = children;
  return n;
}
`;

let out = header;
const names = [];
const catalog = [];
for (const s of [...shaderRegistry].sort((a, b) => a.name.localeCompare(b.name))) {
  const def = s.definition;
  const props = def.props ?? {};
  names.push(s.name);
  out += `\nexport interface ${s.name}Props extends LayerProps {\n`;
  const cprops = [];
  for (const [k, p] of Object.entries(props)) {
    const def = JSON.stringify(p.default);
    out += `  /** ${doc(p.description)}${def !== undefined ? ` Default: ${doc(def).slice(0, 120)}` : ''} */\n`;
    out += `  ${k}?: ${propType(p)};\n`;
    const ui = p.ui ?? {};
    const kinds = Array.isArray(ui.type) ? ui.type : [ui.type ?? 'hidden'];
    cprops.push({
      name: k, kind: kinds[0], mappable: kinds.includes('map'), default: p.default, label: ui.label ?? k,
      group: ui.group, min: ui.min, max: ui.max, step: ui.step,
      options: ui.options?.map((o) => (typeof o === 'object' ? o : { label: String(o), value: o })),
      compileTime: !!p.compileTime,
    });
  }
  out += `}\n\n/** ${doc(s.description)} (${s.category}${s.requiresChild ? '; filters its children' : ''}) */\n`;
  out += `export function ${s.name}(props?: ${s.name}Props, children?: ShaderNode[]): ShaderNode {\n  return node('${s.name}', props, children);\n}\n`;
  catalog.push({ name: s.name, category: s.category, description: s.description, requiresChild: !!s.requiresChild, props: cprops });
}
for (const [oldName, newName] of Object.entries(deprecatedShaderNames ?? {})) {
  out += `\n/** @deprecated renamed to ${newName} */\nexport const ${oldName} = ${newName};\n`;
}
out += `\n/** Names of every built-in effect. */\nexport const SHADER_NAMES: string[] = [\n${names.map((n) => `  '${n}',`).join('\n')}\n];\n`;

const compFile = `${root}/app/webgpu-effects/src/main/ets/components/components.ts`;
writeFileSync(compFile, out);
const catFile = `${root}/app/entry/src/main/resources/rawfile/catalog.json`;
mkdirSync(dirname(catFile), { recursive: true });
writeFileSync(catFile, JSON.stringify(catalog));
console.log(`${names.length} components → ${compFile}\ncatalog → ${catFile}`);
